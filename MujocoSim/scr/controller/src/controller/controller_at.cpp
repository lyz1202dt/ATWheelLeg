Eigen::MatrixXd make_lqr_at_a(const std::size_t table_index)
{
    Eigen::MatrixXd a = Eigen::MatrixXd::Zero(kLqrStateSize, kLqrStateSize);
    a(0, 1) = 1.0;
    a(2, 3) = 1.0;
    a(4, 5) = 1.0;
    a(6, 7) = 1.0;
    a(8, 9) = 1.0;

    const auto& values = kAtATable[table_index];
    a(1, 4) = values[0];
    a(1, 6) = values[1];
    a(3, 4) = values[2];
    a(3, 6) = values[3];
    a(5, 4) = values[4];
    a(5, 6) = values[5];
    a(7, 4) = values[6];
    a(7, 6) = values[7];
    a(9, 4) = values[8];
    a(9, 6) = values[9];
    a(9, 8) = values[10];
    return a;
}

Eigen::MatrixXd make_lqr_at_b(const std::size_t table_index)
{
    Eigen::MatrixXd b = Eigen::MatrixXd::Zero(kLqrStateSize, kLqrInputSize);
    const auto& values = kAtBTable[table_index];
    std::size_t value_index = 0U;
    for (const Eigen::Index row : {1, 3, 5, 7, 9}) {
        for (Eigen::Index column = 0; column < static_cast<Eigen::Index>(kLqrInputSize); ++column) {
            b(row, column) = values[value_index++];
        }
    }
    return b;
}

struct GridCoordinate {
    std::size_t lower_index{0U};
    std::size_t upper_index{0U};
    double fraction{0.0};
};

bool locate_grid_coordinate(const double value, GridCoordinate& coordinate)
{
    if (!std::isfinite(value)) {
        return false;
    }

    if (value <= kAtLegLengths.front()) {
        coordinate = GridCoordinate{};
        return true;
    }
    if (value >= kAtLegLengths.back()) {
        coordinate.lower_index = kAtLegGridSize - 1U;
        coordinate.upper_index = kAtLegGridSize - 1U;
        coordinate.fraction = 0.0;
        return true;
    }

    const auto upper = std::upper_bound(kAtLegLengths.begin(), kAtLegLengths.end(), value);
    coordinate.upper_index = static_cast<std::size_t>(
        std::distance(kAtLegLengths.begin(), upper));
    coordinate.lower_index = coordinate.upper_index - 1U;
    coordinate.fraction =
        (value - kAtLegLengths[coordinate.lower_index]) /
        (kAtLegLengths[coordinate.upper_index] -
         kAtLegLengths[coordinate.lower_index]);
    return std::isfinite(coordinate.fraction);
}

template <typename GainTable>
bool interpolate_gain(const double left_leg_length,
                      const double right_leg_length,
                      const GainTable& gain_table,
                      AtGainMatrix& gain)
{
    GridCoordinate left;
    GridCoordinate right;
    if (!locate_grid_coordinate(left_leg_length, left) ||
        !locate_grid_coordinate(right_leg_length, right)) {
        return false;
    }

    const auto table_index = [](const std::size_t left_index,
                                const std::size_t right_index) {
        return left_index * kAtLegGridSize + right_index;
    };
    const double left_weight = left.fraction;
    const double right_weight = right.fraction;
    const double w00 = (1.0 - left_weight) * (1.0 - right_weight);
    const double w10 = left_weight * (1.0 - right_weight);
    const double w01 = (1.0 - left_weight) * right_weight;
    const double w11 = left_weight * right_weight;

    gain = w00 * gain_table[table_index(left.lower_index, right.lower_index)] +
           w10 * gain_table[table_index(left.upper_index, right.lower_index)] +
           w01 * gain_table[table_index(left.lower_index, right.upper_index)] +
           w11 * gain_table[table_index(left.upper_index, right.upper_index)];
    return gain.allFinite();
}

bool discrete_at_model(const double left_leg_length,
                       const double right_leg_length,
                       Eigen::Matrix<double, 10, 10>& ad,
                       Eigen::Matrix<double, 10, 4>& bd)
{
    GridCoordinate left;
    GridCoordinate right;
    if (!locate_grid_coordinate(left_leg_length, left) ||
        !locate_grid_coordinate(right_leg_length, right)) {
        return false;
    }
    const auto index = [](std::size_t l, std::size_t r) {
        return l * kAtLegGridSize + r;
    };
    const double wl = left.fraction;
    const double wr = right.fraction;
    const double w00 = (1.0 - wl) * (1.0 - wr);
    const double w10 = wl * (1.0 - wr);
    const double w01 = (1.0 - wl) * wr;
    const double w11 = wl * wr;
    const Eigen::Matrix<double, 10, 10> ac =
        w00 * make_lqr_at_a(index(left.lower_index, right.lower_index)) +
        w10 * make_lqr_at_a(index(left.upper_index, right.lower_index)) +
        w01 * make_lqr_at_a(index(left.lower_index, right.upper_index)) +
        w11 * make_lqr_at_a(index(left.upper_index, right.upper_index));
    const Eigen::Matrix<double, 10, 4> bc =
        w00 * make_lqr_at_b(index(left.lower_index, right.lower_index)) +
        w10 * make_lqr_at_b(index(left.upper_index, right.lower_index)) +
        w01 * make_lqr_at_b(index(left.lower_index, right.upper_index)) +
        w11 * make_lqr_at_b(index(left.upper_index, right.upper_index));

    // exp([Ac Bc; 0 0] * dt) = [Ad Bd; 0 I] for a zero-order held input.
    Eigen::Matrix<double, 14, 14> augmented = Eigen::Matrix<double, 14, 14>::Zero();
    augmented.topLeftCorner<10, 10>() = ac;
    augmented.topRightCorner<10, 4>() = bc;
    Eigen::Matrix<double, 14, 14> scaled = augmented * 0.002;
    int squarings = 0;
    while (scaled.cwiseAbs().rowwise().sum().maxCoeff() > 0.5) {
        scaled *= 0.5;
        ++squarings;
    }
    Eigen::Matrix<double, 14, 14> discrete = Eigen::Matrix<double, 14, 14>::Identity();
    Eigen::Matrix<double, 14, 14> term = discrete;
    bool converged = false;
    for (int n = 1; n <= 40; ++n) {
        term = (term * scaled).eval() / static_cast<double>(n);
        discrete += term;
        if (term.cwiseAbs().maxCoeff() < 1e-16) {
            converged = true;
            break;
        }
    }
    if (!converged) {
        return false;
    }
    for (int i = 0; i < squarings; ++i) {
        discrete = (discrete * discrete).eval();
    }
    ad = discrete.topLeftCorner<10, 10>();
    bd = discrete.topRightCorner<10, 4>();
    return ad.allFinite() && bd.allFinite();
}

template <typename Interface>
Interface* find_interface(std::vector<Interface>& interfaces, const std::string& name) {
    const auto iterator =
        std::find_if(interfaces.begin(), interfaces.end(), [&name](const auto& interface) { return interface.get_name() == name; });
    return iterator == interfaces.end() ? nullptr : &(*iterator);
}

inline float rad2angle(float rad) { return rad * 180.0f / 3.14159265f; }
inline float angle2rad(float rad) { return rad * 3.14159265f / 180.0f; }

template <size_t Size>
bool parameter_to_array(const rclcpp::Parameter& parameter,
                        std::array<float, Size>& values,
                        std::string& error) {
    std::vector<double> parameter_values;
    if (parameter.get_type() == rclcpp::ParameterType::PARAMETER_DOUBLE_ARRAY) {
        parameter_values = parameter.as_double_array();
    } else if (parameter.get_type() == rclcpp::ParameterType::PARAMETER_INTEGER_ARRAY) {
        const auto integer_values = parameter.as_integer_array();
        parameter_values.reserve(integer_values.size());
        for (const int64_t value : integer_values) {
            parameter_values.push_back(static_cast<double>(value));
        }
    } else {
        error = parameter.get_name() + " must be a numeric array";
        return false;
    }

    if (parameter_values.size() != Size) {
        error = parameter.get_name() + " must contain exactly " +
                std::to_string(Size) + " values";
        return false;
    }

    for (size_t index = 0; index < Size; ++index) {
        const float value = static_cast<float>(parameter_values[index]);
        if (!std::isfinite(parameter_values[index]) || !std::isfinite(value)) {
            error = parameter.get_name() + " contains a non-finite value";
            return false;
        }
        values[index] = value;
    }
    return true;
}

